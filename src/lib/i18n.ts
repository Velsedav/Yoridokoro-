export function interpolateTranslation(
    translation: string,
    variables?: Record<string, string | number>,
): string {
    if (!variables) return translation;
    return Object.entries(variables).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
        translation,
    );
}

export function useTranslation() {
    const { language } = useSettings();

    const t = (key: string, variables?: Record<string, string | number>): string => {
        const langDict = pt[language] || pt['en'];
        // Return empty string when missing so callers with a `t('x') || 'fallback'`
        // pattern see their fallback instead of the raw key bleeding into the UI.
        const translation = langDict[key] || pt['en'][key] || '';
        return interpolateTranslation(translation, variables);
    };

    return { t };
}
